"""Write docs/TOOLS.md from the tools the server registers (all of them: drive and results tools included).

    python scripts/gen_tools_doc.py [output]
"""
import asyncio
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from backseat_champions_mcp import __version__  # noqa: E402
from backseat_champions_mcp.client import Config  # noqa: E402
from backseat_champions_mcp.server import build_server  # noqa: E402

GATED = {"drive": "BC_ALLOW_DRIVE=1", "release_drive": "BC_ALLOW_DRIVE=1",
         "list_race_results": "BC_RESULTS_PORT set", "get_race_result": "BC_RESULTS_PORT set"}


def type_of(schema):
    if "anyOf" in schema:
        return " or ".join(type_of(s) for s in schema["anyOf"])
    t = schema.get("type", "any")
    if t == "array":
        return "array of " + type_of(schema.get("items", {}))
    return t


def constraints(schema):
    parts = []
    for key, label in (("minimum", ">="), ("exclusiveMinimum", ">"), ("maximum", "<="), ("exclusiveMaximum", "<")):
        if key in schema:
            parts.append("%s %s" % (label, schema[key]))
    for sub in schema.get("anyOf", []):
        parts.extend(constraints(sub))
    return parts


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


async def render():
    config = Config(allow_drive=True, results_port=0, results_dir=os.devnull)
    server = build_server(config)
    tools = await server.list_tools()
    out = ["# Tools", "",
           "Generated by `scripts/gen_tools_doc.py` from the tools registered by backseat-champions-mcp %s. "
           "Do not edit by hand." % __version__, "",
           "Every tool returns compact JSON text. Failures are `{ok: false, error_reason, explanation, hint}` and are "
           "flagged as tool errors. Read tools report `age_s` (seconds since the packet arrived).", "",
           "| Tool | Kind | Summary |", "|---|---|---|"]
    for t in tools:
        kind = "read" if t.annotations and t.annotations.read_only_hint else "write"
        if t.name in GATED:
            kind += " (only with %s)" % GATED[t.name]
        out.append("| [`%s`](#%s) | %s | %s |" % (t.name, t.name, kind, cell(t.description.strip().splitlines()[0])))
    for t in tools:
        out += ["", "## %s" % t.name, ""]
        a = t.annotations
        hints = []
        if a is not None:
            for field, label in (("read_only_hint", "readOnly"), ("destructive_hint", "destructive"),
                                 ("idempotent_hint", "idempotent"), ("open_world_hint", "openWorld")):
                value = getattr(a, field)
                if value is not None:
                    hints.append("%s=%s" % (label, str(value).lower()))
        if t.name in GATED:
            out += ["*Registered only with %s.*" % GATED[t.name], ""]
        out += ["Annotations: %s" % ", ".join(hints), ""]
        out += [line[4:] if line.startswith("    ") else line for line in t.description.strip().splitlines()]
        props = (t.input_schema or {}).get("properties", {})
        required = set((t.input_schema or {}).get("required", []))
        out.append("")
        if not props:
            out.append("Parameters: none.")
            continue
        out += ["| Parameter | Type | Default | Description |", "|---|---|---|---|"]
        for name, schema in props.items():
            default = "required" if name in required else "`%s`" % json.dumps(schema.get("default"))
            desc = schema.get("description", "")
            extra = constraints(schema)
            if extra:
                desc += " (%s)" % ", ".join(extra)
            out.append("| `%s` | %s | %s | %s |" % (name, type_of(schema), default, cell(desc)))
    resources = await server.list_resource_templates()
    fixed = await server.list_resources()
    out += ["", "## Resources", ""]
    for r in resources:
        out.append("- `%s`: %s" % (r.uri_template, r.description))
    for r in fixed:
        out.append("- `%s`: %s" % (r.uri, r.description))
    prompts = await server.list_prompts()
    out += ["", "## Prompts", ""]
    for p in prompts:
        out.append("- `%s`: %s" % (p.name, p.description))
    return "\n".join(out) + "\n"


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs", "TOOLS.md")
    text = asyncio.run(render())
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s" % path, file=sys.stderr)


if __name__ == "__main__":
    main()
